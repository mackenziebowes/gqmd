// Prints the code point ranges of qmd's CJK_CHAR_PATTERN as Goose source (cjk.goose).
// Run: node gen/cjk-ranges.mjs > cjk.goose
const re = /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}]/u;
const ranges = [];
let start = -1;
for (let cp = 0; cp <= 0x10ffff; cp++) {
  if (cp >= 0xd800 && cp <= 0xdfff) { if (start >= 0) { ranges.push([start, cp - 1]); start = -1; } continue; }
  const hit = re.test(String.fromCodePoint(cp));
  if (hit && start < 0) start = cp;
  if (!hit && start >= 0) { ranges.push([start, cp - 1]); start = -1; }
}
if (start >= 0) ranges.push([start, 0x10ffff]);
console.log(`// Generated by gen/cjk-ranges.mjs on Node ${process.version} (Unicode ${process.versions.unicode}). Do not edit.`);
console.log(`// The code points of qmd's CJK_CHAR_PATTERN: Han, Hiragana, Katakana, Hangul by Script.`);
console.log(`namespace cjk;`);
console.log(``);
console.log(`let RANGES: i64[${ranges.length * 2}] = [`);
for (let i = 0; i < ranges.length; i += 4) {
  console.log("    " + ranges.slice(i, i + 4).map(([a, b]) => `${a}, ${b}`).join(", ") + ",");
}
console.log(`];`);
